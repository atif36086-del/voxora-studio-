import { jsPDF } from 'jspdf';
import JSZip from 'jszip';
import { WorkflowChunk, DetectedEpisode } from './types';

/**
 * Builds clean plain-text Hinglish script formatted by episode and chunk.
 */
export function buildFormattedHinglishText(
  projectName: string,
  episodes: DetectedEpisode[],
  chunks: WorkflowChunk[]
): string {
  const lines: string[] = [];
  lines.push(`================================================================`);
  lines.push(`${projectName.toUpperCase()} - HINGLISH ANIME SCRIPT`);
  lines.push(`Voiceover Script • Generated by VOXORA Studio`);
  lines.push(`Exported on: ${new Date().toLocaleString()}`);
  lines.push(`================================================================\n`);

  // Group chunks by episode
  const episodesMap = new Map<number, WorkflowChunk[]>();
  for (const c of chunks) {
    if (!episodesMap.has(c.episodeNumber)) {
      episodesMap.set(c.episodeNumber, []);
    }
    episodesMap.get(c.episodeNumber)!.push(c);
  }

  for (const [epNum, epChunks] of Array.from(episodesMap.entries())) {
    const epMeta = episodes.find((e) => e.episodeNumber === epNum);
    const title = epMeta?.title || `Episode ${epNum}`;
    lines.push(`\n----------------------------------------------------------------`);
    lines.push(`### ${title.toUpperCase()} ###`);
    lines.push(`----------------------------------------------------------------\n`);

    for (const chunk of epChunks) {
      const textToUse = (chunk.translatedText || chunk.originalText || '').trim();
      if (textToUse) {
        lines.push(textToUse);
        lines.push(''); // Blank line between chunks
      }
    }
  }

  return lines.join('\n');
}

/**
 * Generates a clean, multi-page PDF document of the translated script.
 */
export function generateScriptPdfBlob(
  projectName: string,
  episodes: DetectedEpisode[],
  chunks: WorkflowChunk[]
): Blob {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 45;
  const contentWidth = pageWidth - margin * 2;
  let cursorY = margin;

  // Header Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(15, 23, 42); // slate-900
  doc.text(projectName, margin, cursorY);
  cursorY += 22;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139); // slate-500
  doc.text(
    `VOXORA Voiceover Script (Roman Hinglish) • Exported: ${new Date().toLocaleDateString()}`,
    margin,
    cursorY
  );
  cursorY += 18;

  // Divider line
  doc.setDrawColor(226, 232, 240); // hairline border
  doc.setLineWidth(1);
  doc.line(margin, cursorY, pageWidth - margin, cursorY);
  cursorY += 20;

  // Group chunks by episode
  const episodesMap = new Map<number, WorkflowChunk[]>();
  for (const c of chunks) {
    if (!episodesMap.has(c.episodeNumber)) {
      episodesMap.set(c.episodeNumber, []);
    }
    episodesMap.get(c.episodeNumber)!.push(c);
  }

  for (const [epNum, epChunks] of Array.from(episodesMap.entries())) {
    const epMeta = episodes.find((e) => e.episodeNumber === epNum);
    const title = epMeta?.title || `Episode ${epNum}`;

    // Episode Banner
    if (cursorY > pageHeight - 120) {
      doc.addPage();
      cursorY = margin;
    }

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(37, 99, 235); // brand blue
    doc.text(title.toUpperCase(), margin, cursorY);
    cursorY += 16;

    for (const chunk of epChunks) {
      const textToUse = (chunk.translatedText || chunk.originalText || '').trim();
      if (!textToUse) continue;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10.5);
      doc.setTextColor(30, 41, 59); // slate-800

      // Split text to fit page width
      const splitLines = doc.splitTextToSize(textToUse, contentWidth);

      for (const line of splitLines) {
        if (cursorY > pageHeight - margin - 20) {
          doc.addPage();
          cursorY = margin;
        }
        doc.text(line, margin, cursorY);
        cursorY += 15;
      }

      cursorY += 10; // Space between chunks
    }

    cursorY += 14;
  }

  // Add Page Numbers
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFontSize(9);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `Page ${i} of ${totalPages}`,
      pageWidth / 2,
      pageHeight - 20,
      { align: 'center' }
    );
  }

  return doc.output('blob');
}

/**
 * Downloads a raw blob or data URL to the user's browser.
 */
export function triggerFileDownload(
  data: Blob | string,
  fileName: string,
  mimeType = 'application/octet-stream'
) {
  const url =
    typeof data === 'string'
      ? data.startsWith('data:')
        ? data
        : `data:${mimeType};base64,${data}`
      : URL.createObjectURL(data);

  const link = document.createElement('a');
  link.href = url;
  link.download = fileName;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);

  if (typeof data !== 'string') {
    setTimeout(() => URL.revokeObjectURL(url), 5000);
  }
}

/**
 * Builds and triggers download of the full Master ZIP Bundle:
 * 1. translated_script.txt
 * 2. translated_script.pdf
 * 3. final_audio.mp3 (and WAV if available)
 */
export async function downloadMasterZipBundle(
  projectName: string,
  episodes: DetectedEpisode[],
  chunks: WorkflowChunk[],
  mp3Base64?: string,
  wavBase64?: string,
  mp3Url?: string,
  wavUrl?: string
): Promise<void> {
  const zip = new JSZip();

  // 1. Text file
  const fullText = buildFormattedHinglishText(projectName, episodes, chunks);
  zip.file('translated_script.txt', fullText);

  // 2. PDF file
  const pdfBlob = generateScriptPdfBlob(projectName, episodes, chunks);
  const pdfArrayBuffer = await pdfBlob.arrayBuffer();
  zip.file('translated_script.pdf', pdfArrayBuffer);

  // 3. Audio file
  if (mp3Url) {
    try {
      const res = await fetch(mp3Url);
      const ab = await res.arrayBuffer();
      zip.file('final_audio.mp3', ab);
    } catch (e) {
      console.error('Error fetching mp3Url for zip:', e);
    }
  } else if (mp3Base64) {
    const mp3Binary = atob(mp3Base64);
    const mp3Bytes = new Uint8Array(mp3Binary.length);
    for (let i = 0; i < mp3Binary.length; i++) {
      mp3Bytes[i] = mp3Binary.charCodeAt(i);
    }
    zip.file('final_audio.mp3', mp3Bytes.buffer);
  } else if (wavUrl) {
    try {
      const res = await fetch(wavUrl);
      const ab = await res.arrayBuffer();
      zip.file('final_audio.wav', ab);
    } catch (e) {
      console.error('Error fetching wavUrl for zip:', e);
    }
  } else if (wavBase64) {
    const wavBinary = atob(wavBase64);
    const wavBytes = new Uint8Array(wavBinary.length);
    for (let i = 0; i < wavBinary.length; i++) {
      wavBytes[i] = wavBinary.charCodeAt(i);
    }
    zip.file('final_audio.wav', wavBytes.buffer);
  }

  // Generate ZIP blob
  const zipBlob = await zip.generateAsync({ type: 'blob' });
  const cleanName = projectName.replace(/[^a-zA-Z0-9_-]/g, '_') || 'VOXORA';
  triggerFileDownload(zipBlob, `${cleanName}_Master_Bundle.zip`, 'application/zip');
}
